/**
 * One-time generator for #46's data half of the migration.
 *
 * Reads the vendored JSON in this directory (see README.md for provenance) and prints INSERT
 * statements for province → district → subdistrict → subdistrict_postal_code, in that order so
 * every foreign key is satisfied by the time it is needed.
 *
 * This is a build-time tool, not part of the running app — it was run once, its stdout was
 * appended to `prisma/migrations/<timestamp>_add_area_reference/migration.sql` by hand, and that
 * migration file (not this script) is the durable artifact CLAUDE.md's "never edit a committed
 * migration" rule protects from here on. Kept in the repo so a real administrative boundary
 * change can regenerate the *data* half of a brand new migration the same way, without hand-
 * writing thousands of INSERT lines again — see this directory's README for that procedure.
 *
 * Run with: `node --loader ts-node/esm prisma/reference-data/thai-geography/generate-migration-sql.ts`
 */
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { newId } from '../../../src/common/id.js';

const here = dirname(fileURLToPath(import.meta.url));

interface ProvinceRow {
  id: number;
  name_th: string;
}
interface DistrictRow {
  id: number;
  name_th: string;
  province_id: number;
}
interface SubDistrictRow {
  id: number;
  zip_code: number;
  name_th: string;
  district_id: number;
}

function readJson<T>(fileName: string): T {
  return JSON.parse(readFileSync(join(here, fileName), 'utf8')) as T;
}

/** Postgres string literal, single-quoted with `'` doubled — every name here is untrusted input. */
function sqlString(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}

function main(): void {
  const provinces = readJson<ProvinceRow[]>('province.json');
  const districts = readJson<DistrictRow[]>('district.json');
  const subdistricts = readJson<SubDistrictRow[]>('sub_district.json');

  // Checked here, at generation time, rather than assumed: this ticket's own acceptance criteria
  // requires the *schema* to allow more than one postal code per subdistrict, and the honest
  // seed is whatever this source actually contains — not a fabricated second code to exercise a
  // path the source itself never needs. README.md and DECISIONS.md both record the result.
  const zipCodesBySubdistrict = new Map<number, Set<number>>();
  for (const row of subdistricts) {
    const set = zipCodesBySubdistrict.get(row.id) ?? new Set<number>();
    set.add(row.zip_code);
    zipCodesBySubdistrict.set(row.id, set);
  }
  const multiZip = [...zipCodesBySubdistrict.values()].filter((set) => set.size > 1);
  console.error(
    `# ${multiZip.length} of ${subdistricts.length} subdistricts have more than one postal code in this source.`,
  );

  const provinceIds = new Map<number, string>();
  const districtIds = new Map<number, string>();
  const subdistrictIds = new Map<number, string>();

  const lines: string[] = [];
  lines.push('-- Data for #46: province → district → subdistrict → subdistrict_postal_code');
  lines.push('-- Generated by prisma/reference-data/thai-geography/generate-migration-sql.ts');
  lines.push('-- Source: kongvut/thai-province-data (MIT) — see the README in that directory.');
  lines.push('');

  lines.push('-- Provinces');
  for (const row of provinces) {
    const id = newId();
    provinceIds.set(row.id, id);
    lines.push(
      `INSERT INTO "province" ("id", "source_code", "name_th") VALUES ` +
        `('${id}', ${row.id}, ${sqlString(row.name_th)});`,
    );
  }

  lines.push('');
  lines.push('-- Districts');
  for (const row of districts) {
    const provinceId = provinceIds.get(row.province_id);
    if (provinceId === undefined) {
      throw new Error(`District ${row.id} references unknown province ${row.province_id}`);
    }
    const id = newId();
    districtIds.set(row.id, id);
    lines.push(
      `INSERT INTO "district" ("id", "source_code", "name_th", "province_id") VALUES ` +
        `('${id}', ${row.id}, ${sqlString(row.name_th)}, '${provinceId}');`,
    );
  }

  lines.push('');
  lines.push('-- Subdistricts');
  for (const row of subdistricts) {
    const districtId = districtIds.get(row.district_id);
    if (districtId === undefined) {
      throw new Error(`Subdistrict ${row.id} references unknown district ${row.district_id}`);
    }
    const id = newId();
    subdistrictIds.set(row.id, id);
    lines.push(
      `INSERT INTO "subdistrict" ("id", "source_code", "name_th", "district_id") VALUES ` +
        `('${id}', ${row.id}, ${sqlString(row.name_th)}, '${districtId}');`,
    );
  }

  lines.push('');
  lines.push('-- Postal codes (deduplicated per subdistrict, see the check logged above)');
  for (const [sourceSubdistrictId, zipCodes] of zipCodesBySubdistrict) {
    const subdistrictId = subdistrictIds.get(sourceSubdistrictId);
    if (subdistrictId === undefined) {
      throw new Error(`Unknown subdistrict ${sourceSubdistrictId} while writing postal codes`);
    }
    for (const zipCode of zipCodes) {
      const id = newId();
      lines.push(
        `INSERT INTO "subdistrict_postal_code" ("id", "subdistrict_id", "postal_code") VALUES ` +
          `('${id}', '${subdistrictId}', ${sqlString(String(zipCode))});`,
      );
    }
  }

  console.log(lines.join('\n'));
}

main();
