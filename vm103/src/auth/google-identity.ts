/**
 * The only way this system talks to Google (#26).
 *
 * The same shape as `EmailSender`: an abstract class so Nest has a token to inject against, one
 * implementation wired in the module, and domain code that never mentions the provider. The reason
 * is the same too — a test cannot drive a sign-in that requires a real browser consenting on
 * accounts.google.com, and the alternative to an interface is a `NODE_ENV === 'test'` branch in the
 * production path, which is the branch that eventually ships enabled.
 *
 * ⚠️ This is **not** a third test seam. M5 allows exactly two ways into the system (the HTTP edge
 * and the Clock/sweep point) and says in as many words that a fake `EmailSender` does not count as
 * another one. This is the same kind of thing: an outbound adapter to somebody else's server,
 * replaced so the suite does not post to it. Tests still arrive through `GET /auth/google/callback`
 * like a browser does, and every rule about linking accounts is exercised on that path.
 */
export abstract class GoogleIdentity {
  /**
   * Where to send the browser to ask Google who it is.
   *
   * `state` is generated by the caller and echoed back by Google; see oauth-state.ts for what it
   * is for.
   */
  abstract authorisationUrl(state: string): string;

  /**
   * Trades the one-time `code` Google redirected back with for the account behind it.
   *
   * Returns a result rather than throwing, for the same reason `EmailSender` does: a failure here
   * is ordinary (an expired code, a user who pressed back, Google being down) and the controller
   * has to turn it into a redirect the person can read, not a stack trace.
   */
  abstract exchangeCode(code: string): Promise<GoogleExchangeResult>;
}

/** What Google says about the person who just consented. */
export interface GoogleAccount {
  /** Already lowercased and trimmed by the implementation — `normaliseEmail`, same as ours. */
  readonly email: string;

  /**
   * Google's own `email_verified` claim.
   *
   * Load-bearing, not informational. Every linking rule in #26 rests on it: an address Google has
   * not verified is an address Google is merely repeating back from a profile, and treating it as
   * proof would let a Workspace domain admin — or anyone with a self-hosted OIDC-ish setup — claim
   * somebody else's account here.
   */
  readonly emailVerified: boolean;

  /**
   * Google's stable identifier for the account (`sub`).
   *
   * §101: stored as `user.google_subject` once an account is connected to Google, and what a
   * connected account is recognised by — an address alone can come back attached to a different
   * Google account (a workplace account deleted and recreated).
   */
  readonly subject: string;
}

export type GoogleExchangeResult =
  | { readonly ok: true; readonly account: GoogleAccount }
  | {
      readonly ok: false;
      /** For the server log, never for a response. Must not contain the code or any token. */
      readonly reason: string;
    };
